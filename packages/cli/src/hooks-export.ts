// why: output format follows the official Claude Code hooks reference (PreToolUse), see HOOK_DOC_URL.
export const HOOK_DOC_URL = 'https://code.claude.com/docs/en/hooks';

export interface HookOp {
  name: string;
  risk_level: string;
  reason: string;
  decision?: 'allow' | 'ask' | 'deny';
  policy_reason?: string;
}

export function buildHookScript(server: string, ops: HookOp[]): string {
  const map: Record<string, { risk: string; reason: string; decision: string; policy_reason?: string }> = {};
  for (const op of ops) {
    map[op.name] = {
      risk: op.risk_level,
      reason: op.reason,
      decision: op.decision ?? (op.risk_level === 'confirmation' ? 'ask' : 'allow'),
      ...(op.policy_reason ? { policy_reason: op.policy_reason } : {}),
    };
  }
  return `#!/usr/bin/env node
// @generated by "ars hooks export" - do not edit
// why: "allow" skips Claude Code's normal permission prompt on purpose; each decision was resolved at export time from the schema's risk_level and, when given, the agent policy.
// invariant: unknown tools produce no output and exit 0, so Claude Code keeps its normal permission flow.
const SERVER = ${JSON.stringify(server)};
const OPERATIONS = ${JSON.stringify(map, null, 2)};

let raw = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (c) => { raw += c; });
process.stdin.on('end', () => {
  let event;
  try { event = JSON.parse(raw); } catch { process.exit(0); }
  const prefix = 'mcp__' + SERVER + '__';
  const tool = event && typeof event.tool_name === 'string' ? event.tool_name : '';
  if (!tool.startsWith(prefix)) process.exit(0);
  const name = tool.slice(prefix.length);
  const entry = Object.prototype.hasOwnProperty.call(OPERATIONS, name) ? OPERATIONS[name] : undefined;
  if (!entry) process.exit(0);
  const confirm = entry.risk === 'confirmation';
  const decision = entry.decision;
  const out = {
    hookSpecificOutput: {
      hookEventName: 'PreToolUse',
      permissionDecision: decision,
    },
  };
  const input = event && event.tool_input && typeof event.tool_input === 'object' ? event.tool_input : {};
  const render = (t) => t.replace(/\\{\\{\\s*(\\w+)\\s*\\}\\}/g, (m, k) => (input[k] === undefined || input[k] === null ? m : String(input[k])));
  if (decision !== 'allow' && entry.policy_reason) out.hookSpecificOutput.permissionDecisionReason = entry.policy_reason;
  else if (decision === 'ask' && confirm) out.hookSpecificOutput.permissionDecisionReason = render(entry.reason);
  process.stdout.write(JSON.stringify(out) + '\\n');
});
`;
}

export function buildSettingsSnippet(server: string, scriptPath: string) {
  return {
    hooks: {
      PreToolUse: [
        {
          matcher: `mcp__${server}__.*`,
          hooks: [{ type: 'command', command: `node ${JSON.stringify(scriptPath)}` }],
        },
      ],
    },
  };
}
